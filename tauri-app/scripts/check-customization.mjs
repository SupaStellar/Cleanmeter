import { chromium } from 'playwright';
import assert from 'node:assert/strict';
const browser = await chromium.launch({channel: 'chrome'});
const page = await browser.newPage({viewport:{width:720,height:1000}});
const errors = []; page.on('pageerror',e => errors.push(e.message));
const url = process.env.CLEANMETER_PREVIEW_URL || 'http://localhost:1445';
await page.goto(url);
await page.getByRole('tab',{name:'Style',exact:true}).click();
await page.getByRole('heading',{name:'Make it yours'}).waitFor();
const editor = page.locator('.customization-editor');
const state = async () => page.evaluate(async () => (await import('/src/stores/settings-store.ts')).useSettingsStore.getState().settings);
await editor.getByRole('button',{name:'Presets',exact:true}).click();
await editor.getByRole('button',{name:'Terminal',exact:true}).click();
assert.equal((await state()).appearance.font,'Consolas');
assert.equal((await state()).appearance.enabled,true);
assert.equal(await page.locator('[data-overlay-hud]').evaluate(el=>getComputedStyle(el).getPropertyValue('--overlay-font')), '"Consolas", Inter, sans-serif');
await editor.getByRole('button',{name:'Layout',exact:true}).click();
await editor.getByRole('button',{name:'Move NET earlier'}).click();
assert.deepEqual((await state()).appearance.order,['FPS','CPU','GPU','NET','RAM']);
assert.deepEqual(await page.locator('[data-overlay-hud] > [data-pill]').evaluateAll(els=>els.map(e=>e.dataset.pill)),['FPS','CPU','GPU','NET','RAM']);
await editor.getByRole('button',{name:'Graphs',exact:true}).click();
const gauges = await page.evaluate(async () => (await import('/src/lib/customization/schema.ts')).GAUGES);
for (const gauge of gauges) {
  const title = gauge.replaceAll('-',' ').replace(/^./,c=>c.toUpperCase());
  await editor.getByRole('button',{name:title,exact:true}).click();
  assert.equal((await state()).appearance.gauge,gauge);
  assert.ok(await page.locator(`[data-overlay-hud] [data-gauge-style="${gauge}"]`).count());
}
await editor.getByRole('button',{name:'Appearance',exact:true}).click();
// Exercise an actual DialKit slider with its keyboard interface.
const slider = editor.getByRole('slider',{name:'Stat size',exact:true});
const before=(await state()).fontSizeValue;
await slider.focus(); await page.keyboard.press('ArrowRight');
assert.equal((await state()).fontSizeValue,before+1);
const png = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aA1sAAAAASUVORK5CYII=','base64');
await editor.getByLabel('Inner pills background image',{exact:true}).setInputFiles({name:'test.png',mimeType:'image/png',buffer:png});
await page.waitForFunction(async()=> (await import('/src/stores/settings-store.ts')).useSettingsStore.getState().settings.appearance.inner.image.startsWith('data:image/webp'));
await editor.getByRole('button',{name:'Presets',exact:true}).click();
await editor.getByLabel('Preset name',{exact:true}).fill('Smoke test');
await editor.getByRole('button',{name:'Save current',exact:true}).click();
const saved = await page.evaluate(()=>JSON.parse(localStorage.getItem('cleanmeter.appearance-presets.v1')));
assert.equal(saved[0].name,'Smoke test');
const download = page.waitForEvent('download');
await editor.getByRole('button',{name:'Export file',exact:true}).click();
assert.equal((await download).suggestedFilename(),'Smoke-test.cleanmeter.json');
await editor.getByRole('button',{name:'Restore original style',exact:true}).click();
assert.equal((await state()).appearance.enabled,false);
await editor.getByRole('button',{name:'Undo',exact:true}).click();
assert.equal((await state()).appearance.enabled,true);
const beforeBad = JSON.stringify((await state()).appearance);
await editor.getByLabel('Import preset',{exact:true}).setInputFiles({name:'bad.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify({version:1,name:'Bad',appearance:{inner:{image:'https://tracker.test/a.png'}}}))});
await editor.getByRole('status').filter({hasText:'Preset backgrounds'}).waitFor();
assert.equal(JSON.stringify((await state()).appearance),beforeBad);
await page.reload();await page.getByRole('tab',{name:'Style',exact:true}).click();await editor.getByRole('button',{name:'Presets',exact:true}).click();
await editor.getByRole('button',{name:'Smoke test',exact:true}).click();
assert.equal((await state()).appearance.font,'Consolas');
await editor.getByRole('button',{name:'Graphs',exact:true}).click();
await page.screenshot({path:'/tmp/cleanmeter-customization-graphs.png'});
assert.deepEqual(errors,[]);
console.log('PASS: themes, live preview, order, all 32 gauges, DialKit keyboard slider, image conversion, local persistence, export, unsafe import rejection, undo.');
await browser.close();
